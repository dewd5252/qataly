// ── Zebra-stripe table builder ──
function makeTable(headers, rows) {
  const headerRow = new TableRow({
    tableHeader: true,
    cantSplit: true,
    children: headers.map((h) =>
      new TableCell({
        width: { size: Math.floor(100 / headers.length), type: WidthType.PERCENTAGE },
        borders: allNoBorders,
        shading: { type: ShadingType.CLEAR, fill: "1B6B7A" },
        margins: { top: 60, bottom: 60, left: 120, right: 120 },
        children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, size: 21, color: "FFFFFF", font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })] })],
      })
    ),
  });
  const dataRows = rows.map((cells, idx) =>
    new TableRow({
      cantSplit: true,
      children: cells.map((text) =>
        new TableCell({
          width: { size: Math.floor(100 / headers.length), type: WidthType.PERCENTAGE },
          borders: allNoBorders,
          shading: { type: ShadingType.CLEAR, fill: idx % 2 === 0 ? "EDF3F5" : "FFFFFF" },
          margins: { top: 60, bottom: 60, left: 120, right: 120 },
          children: [new Paragraph({ children: [new TextRun({ text, size: 21, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })] })],
        })
      ),
    })
  );
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: allNoBorders,
    rows: [headerRow, ...dataRows],
  });
}

